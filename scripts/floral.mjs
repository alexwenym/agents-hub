// Draws the green floral background tile and writes it into public/style.css
// (between the floral:start/end markers) as light and dark data URIs.
// Run after changing the design: node scripts/floral.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const r = (n) => Math.round(n * 10) / 10;
function tile(c) {
  const flower = (x, y, s, rot, petal = c.petal, op = c.petalOpacity) =>
    `<g transform='translate(${x} ${y}) rotate(${rot}) scale(${s})'><g fill='${petal}' fill-opacity='${op}'>` +
    [0, 72, 144, 216, 288].map((a) => `<ellipse cy='-12' rx='7.5' ry='12' transform='rotate(${a})'/>`).join('') +
    `</g><circle r='4.5' fill='${c.center}'/></g>`;
  const leaf = (x, y, rot, s, color) =>
    `<path d='M0 0C8-9 24-9 32 0C24 9 8 9 0 0Z' fill='${color}' transform='translate(${r(x)} ${r(y)}) rotate(${r(rot)}) scale(${r(s)})'/>`;
  // a curved stem (quadratic Bezier) with leaves alternating along it, shrinking toward the tip
  const sprig = ([x0, y0], [x1, y1], [x2, y2], n, s0) => {
    const at = (t) => [(1 - t) ** 2 * x0 + 2 * (1 - t) * t * x1 + t * t * x2, (1 - t) ** 2 * y0 + 2 * (1 - t) * t * y1 + t * t * y2];
    const dir = (t) => Math.atan2(2 * (1 - t) * (y1 - y0) + 2 * t * (y2 - y1), 2 * (1 - t) * (x1 - x0) + 2 * t * (x2 - x1)) * 180 / Math.PI;
    let out = `<path d='M${x0} ${y0}Q${x1} ${y1} ${x2} ${y2}' fill='none' stroke='${c.stem}' stroke-width='1.6' stroke-linecap='round'/>`;
    for (let i = 0; i < n; i++) {
      const t = 0.12 + (0.78 * i) / n;
      const [x, y] = at(t);
      out += leaf(x, y, dir(t) + (i % 2 ? 50 : -50), s0 * (1 - 0.35 * t), i % 2 ? c.leaf : c.leafDark);
    }
    return out;
  };
  return `<svg xmlns='http://www.w3.org/2000/svg' width='280' height='280' viewBox='0 0 280 280'>` +
    sprig([40, 250], [36, 170], [128, 140], 6, 0.95) + flower(130, 138, 1.05, 10) +
    sprig([150, 118], [204, 112], [228, 52], 4, 0.75) + flower(229, 48, 0.75, 30) +
    sprig([186, 252], [236, 238], [250, 192], 3, 0.6) + flower(250, 188, 0.55, 0, c.petal2, c.petal2Opacity) +
    flower(70, 58, 0.7, 15, c.petal2, c.petal2Opacity) + flower(252, 122, 0.45, 40) + flower(112, 226, 0.5, 5, c.petal2, c.petal2Opacity) +
    leaf(84, 72, 20, 0.55, c.leaf) + leaf(60, 72, 150, 0.45, c.leafDark) +
    `<g fill='${c.dot}'>` + [[150, 66, 2], [162, 80, 1.4], [92, 196, 1.8], [24, 118, 1.6], [204, 168, 1.4], [120, 22, 1.6], [264, 262, 1.5], [18, 30, 1.3]]
      .map(([x, y, rr]) => `<circle cx='${x}' cy='${y}' r='${rr}'/>`).join('') + `</g></svg>`;
}
const LIGHT = { base: '#e8f2e1', petal: '#ffffff', petalOpacity: 0.92, petal2: '#d3e9cb', petal2Opacity: 1, leaf: '#b5d6a7', leafDark: '#9cc78d', stem: '#9cc78d', center: '#eedf9c', dot: '#c3dcb6' };
const DARK = { base: '#0f1a12', petal: '#b7dcaa', petalOpacity: 0.17, petal2: '#8fc283', petal2Opacity: 0.13, leaf: '#1f3826', leafDark: '#284a31', stem: '#284a31', center: '#56653a', dot: '#22392a' };

const css = (p) => `--page: ${p.base}; --floral: url("data:image/svg+xml,${encodeURIComponent(tile(p))}");`;
const block =
  '/* floral:start (generated by scripts/floral.mjs) */\n' +
  `:root { ${css(LIGHT)} }\n` +
  `@media (prefers-color-scheme: dark) { :root { ${css(DARK)} } }\n` +
  '/* floral:end */';

const file = new URL('../public/style.css', import.meta.url);
const style = readFileSync(file, 'utf8');
const marked = /\/\* floral:start[\s\S]*?\/\* floral:end \*\//;
if (!marked.test(style)) throw new Error('floral markers not found in public/style.css');
writeFileSync(file, style.replace(marked, block));
console.log('updated public/style.css');
